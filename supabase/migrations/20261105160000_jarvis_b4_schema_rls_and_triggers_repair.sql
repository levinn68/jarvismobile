-- Guard immutable columns against tampering during UPDATE
create or replace function public.jarvis_enforce_immutable_columns()
returns trigger
language plpgsql
security invoker
set search_path = pg_catalog, public
as $$
begin
  if tg_table_name = 'jarvis_conversations' then
    if new.id is distinct from old.id then
      raise exception 'Column id on jarvis_conversations is immutable';
    end if;
    if new.user_id is distinct from old.user_id then
      raise exception 'Column user_id on jarvis_conversations is immutable';
    end if;
    if new.created_at is distinct from old.created_at then
      raise exception 'Column created_at on jarvis_conversations is immutable';
    end if;
    new.updated_at := clock_timestamp();
    return new;
  elsif tg_table_name = 'jarvis_messages' then
    if new.id is distinct from old.id then
      raise exception 'Column id on jarvis_messages is immutable';
    end if;
    if new.user_id is distinct from old.user_id then
      raise exception 'Column user_id on jarvis_messages is immutable';
    end if;
    if new.conversation_id is distinct from old.conversation_id then
      raise exception 'Column conversation_id on jarvis_messages is immutable';
    end if;
    if new.client_id is distinct from old.client_id then
      raise exception 'Column client_id on jarvis_messages is immutable';
    end if;
    if new.created_at is distinct from old.created_at then
      raise exception 'Column created_at on jarvis_messages is immutable';
    end if;
    return new;
  end if;
  return new;
end;
$$;

-- Prepare message insertion: enforce monotonically increasing timestamps within
-- a conversation so batch-inserted (user, assistant) pairs never tie on created_at.
create or replace function public.jarvis_prepare_message_insert()
returns trigger
language plpgsql
security invoker
set search_path = pg_catalog, public
as $$
declare
  v_conv_owner uuid;
  v_next_seq bigint;
  v_latest timestamptz;
begin
  if new.user_id is null then
    new.user_id := auth.uid();
  end if;
  if new.client_id is null then
    new.client_id := gen_random_uuid();
  end if;
  if new.created_at is null then
    new.created_at := clock_timestamp();
  end if;

  select c.user_id
    into v_conv_owner
    from public.jarvis_conversations c
   where c.id = new.conversation_id
   for update;

  if v_conv_owner is null then
    raise exception 'Conversation % does not exist', new.conversation_id
      using errcode = '23503';
  end if;

  if v_conv_owner <> new.user_id then
    raise exception 'Cross-user message insertion is forbidden for conversation %', new.conversation_id
      using errcode = '42501';
  end if;

  if new.sequence_number is null or new.sequence_number <= 0 then
    select coalesce(max(m.sequence_number), 0) + 1
      into v_next_seq
      from public.jarvis_messages m
     where m.conversation_id = new.conversation_id;
    new.sequence_number := v_next_seq;
  end if;

  select max(m.created_at)
    into v_latest
    from public.jarvis_messages m
   where m.conversation_id = new.conversation_id
     and m.user_id = new.user_id;

  if v_latest is not null and new.created_at <= v_latest then
    new.created_at := v_latest + interval '1 millisecond';
  elsif new.role = 'assistant' then
    new.created_at := new.created_at + interval '1 millisecond';
  end if;

  return new;
end;
$$;

-- Replace legacy SECURITY DEFINER trigger function with SECURITY INVOKER
create or replace function public.jarvis_touch_conversation_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = pg_catalog, public
as $$
declare
  v_conv_id uuid;
  v_user_id uuid;
begin
  if tg_table_name = 'jarvis_messages' then
    if tg_op = 'DELETE' then
      v_conv_id := old.conversation_id;
      v_user_id := old.user_id;
    else
      v_conv_id := new.conversation_id;
      v_user_id := new.user_id;
    end if;

    update public.jarvis_conversations c
       set updated_at = clock_timestamp(),
           last_message_at = (
             select max(m.created_at)
               from public.jarvis_messages m
              where m.conversation_id = v_conv_id
                and m.user_id = v_user_id
           ),
           message_count = (
             select count(*)::integer
               from public.jarvis_messages m
              where m.conversation_id = v_conv_id
                and m.user_id = v_user_id
           )
     where c.id = v_conv_id
       and c.user_id = v_user_id;

    if tg_op = 'DELETE' then
      return old;
    end if;
    return new;
  elsif tg_table_name = 'jarvis_conversations' then
    new.updated_at := clock_timestamp();
    return new;
  end if;
  return new;
end;
$$;

